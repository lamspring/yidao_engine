def get_body_nature(hex_val: int) -> str:
    """
    获取卦象的本质描述（体之语库）。
    
    查询优先级：
      1. 高频复合卦 body_nature（24卦覆盖）
      2. 八纯卦 body_nature（8卦覆盖）
      3. fallback：上卦对应的纯卦描述
    
    Args:
        hex_val: 卦值 0-63。
    
    Returns:
        body_nature 描述字符串
    """
    v = int(hex_val) & 0b111111
    if v in BODY_NATURE:
        return BODY_NATURE[v]
    
    # 复合卦 fallback：上卦对应的纯卦
    upper = (v >> 3) & 0b111
    pure_candidates = [0, 9, 18, 27, 36, 45, 54, 63]
    fallback = pure_candidates[upper]
    return BODY_NATURE.get(fallback, "未知之体，尚未被命名。")


def get_contested_nature(pair: Tuple[int, int]) -> str:
    """
    获取交战体的本质描述。
    
    Args:
        pair: 交战卦对 (h1, h2)
    
    Returns:
        如果是先天对卦，返回专属史诗叙事；
        否则返回通用交战体模板生成的描述。
    """
    if not pair or len(pair) != 2:
        return "此域诸力并竞，尚无定体，如洪荒初开。"
    
    # 标准化顺序：大数在前，小数在后
    ordered = (max(pair[0], pair[1]), min(pair[0], pair[1]))
    
    if ordered in CONTESTED_BODY_NATURE:
        return CONTESTED_BODY_NATURE[ordered]
    
    return _build_generic_contested_narrative(pair)


