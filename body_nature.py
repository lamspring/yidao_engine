# 关系类型判定（基于五行与先天结构）
def _classify_trigram_relation(a: int, b: int) -> str:
    """
    判定两个纯卦之间的关系类型。
    返回：'对卦' | '通气' | '相生' | '相克' | '同气' | '杂'
    """
    from codex import get_gua
    
    # 先天对卦
    opposite_pairs = {frozenset([0, 63]), frozenset([9, 27]), frozenset([18, 45]), frozenset([36, 54])}
    if frozenset([a, b]) in opposite_pairs:
        return "对卦"
    
    # 通气（先天相邻）
    breath_pairs = {frozenset([1, 3]), frozenset([4, 6])}  # 震巽、艮兑（已在 opposite 中覆盖，这里保留扩展性）
    
    # 五行映射
    wuxing = {
        0: "土", 9: "木", 18: "水", 27: "木",
        36: "土", 45: "火", 54: "金", 63: "金",
    }
    wa, wb = wuxing.get(a, "?"), wuxing.get(b, "?")
    
    if wa == wb:
        return "同气"
    
    # 五行生克
    sheng = [("木", "火"), ("火", "土"), ("土", "金"), ("金", "水"), ("水", "木")]
    ke = [("木", "土"), ("土", "水"), ("水", "火"), ("火", "金"), ("金", "木")]
    
    if (wa, wb) in sheng or (wb, wa) in sheng:
        return "相生"
    if (wa, wb) in ke or (wb, wa) in ke:
        return "相克"
    
    return "杂"


def _build_generic_contested_narrative(pair: Tuple[int, int]) -> str:
    """
    通用交战体叙事模板。
    当交战对不是先天对卦时，使用此模板生成描述。
    """
    h1, h2 = pair[0] & 0b111111, pair[1] & 0b111111
    
    # 尝试从上下卦提取纯卦特征
    # 如果 h1/h2 不是纯卦，用它们的主导上下卦近似
    from codex import get_gua
    
    def _dominant_trigram(hex_val: int) -> int:
        """返回卦值中阴阳比例更极端的纯卦近似"""
        upper = (hex_val >> 3) & 0b111
        lower = hex_val & 0b111
        # 简单规则：如果上下卦相同，返回该纯卦；否则返回上卦
        if upper == lower:
            return hex_val
        # 映射到纯卦：坤0 震9 坎18 巽27 艮36 离45 兑54 乾63
        pure = [0, 9, 18, 27, 36, 45, 54, 63]
        return pure[upper]
    
    t1 = _dominant_trigram(h1)
    t2 = _dominant_trigram(h2)
    
    name1 = _TRIGRAM_NAMES.get(t1, "?")
    name2 = _TRIGRAM_NAMES.get(t2, "?")
    verb1 = _TRIGRAM_VERBS.get(t1, "作用")
    verb2 = _TRIGRAM_VERBS.get(t2, "作用")
    relation = _classify_trigram_relation(t1, t2)
    
    relation_desc = {
        "对卦": "在对抗中相互定义",
        "通气": "在呼吸中相互流通",
        "相生": "在滋养中相互助长",
        "相克": "在压制中相互消耗",
        "同气": "在共鸣中相互放大",
        "杂": "在纠缠中相互塑造",
    }
    
    return (
        f"此域长期处于 {name1} 与 {name2} 的拉锯之中。"
        f"{name1} 的 {verb1} 之力与 {name2} 的 {verb2} 之力 {relation_desc.get(relation, '相互纠缠')}。"
        f"它的本质不是二者中的任何一个，而是它们之间的那个张力场——"
        f"一个永远无法达成、却永远在逼近的平衡。"
    )


