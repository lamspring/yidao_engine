# 2. 构建完整64卦字典
# ───────────────────────────────────────────

def _build_codex():
    codex = {}
    for v in range(64):
        lower = v & 0b111
        upper = (v >> 3) & 0b111
        name = _64GUA_NAMES_MATRIX[upper][lower]
        b = format(v, '06b')

        if v in _BASE_PRIMITIVES:
            info = dict(_BASE_PRIMITIVES[v])
        else:
            # 复合卦：基于上下卦推导基础信息
            uw, lw = _BAGUA_WUXING[upper], _BAGUA_WUXING[lower]
            up, lp = _BAGUA_PROTOCOL[upper], _BAGUA_PROTOCOL[lower]
            info = {
                "name": name,
                "binary": b,
                "wuxing": f"{uw}/{lw}",
                "nature": "复合态势",
                "protocol": up,  # 以上卦协议为主导（天覆于上）
                "semantic": f"上{_BAGUA_NAMES[upper]}下{_BAGUA_NAMES[lower]}，"
                             f"{up}与{lp}交织之复合场"
            }
        codex[v] = info
    return codex


GUA_DICT = _build_codex()

