def get_gua(value: int) -> dict:
    """根据卦值(0-63)获取卦信息"""
    return GUA_DICT.get(int(value) & 0b111111,
                        {"name": "?", "binary": "??????", "protocol": "未知",
                         "nature": "未知", "semantic": "未知", "wuxing": "?"})

def encode_name(name: str) -> int:
    """根据卦名反查卦值"""
    for v, info in GUA_DICT.items():
        if info["name"] == name:
            return v
    return 0

def get_trigram(value: int) -> tuple:
    """分离上下卦索引 (upper, lower)"""
    v = int(value) & 0b111111
    return (v >> 3) & 0b111, v & 0b111

def get_wuxing(value: int) -> str:
    """获取卦的五行属性"""
    return get_gua(value).get("wuxing", "?")

def get_protocol(value: int) -> str:
    """获取卦的行为协议"""
    return get_gua(value).get("protocol", "复合")

def gua_to_color(value: int) -> tuple:
    """将卦值映射为RGB颜色（用于可视化）"""
    v = int(value) & 0b111111
    yang_cnt = bin(v).count('1')
    ratio = yang_cnt / 6.0
    # 用高位三爻映射基础色调，亮度由阳爻比例决定
    r = int(255 * ((v >> 5) & 1))
    g = int(255 * ((v >> 3) & 1))
    b = int(255 * ((v >> 1) & 1))
    base = int(255 * ratio)
    return (
        int(base * 0.65 + r * 0.35),
        int(base * 0.65 + g * 0.35),
        int(base * 0.65 + b * 0.35)
    )

